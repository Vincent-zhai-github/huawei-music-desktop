// Draws the custom app + tray icons using sharp (pure Node, no Electron needed).
// Design: white rounded square with three layered translucent ellipses (magenta/cyan/blue)
// and a white Lucide "Music" glyph centered on top.
import { mkdir, writeFile } from 'node:fs/promises';
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

function iconNodes(name) {
  const source = readFileSync(join(root, 'node_modules/lucide-react/dist/esm/icons', `${name}.js`), 'utf8');
  const match = /createLucideIcon\("[^"]+",\s*(\[[\s\S]*?\])\s*\);/.exec(source);
  if (!match) throw new Error(`cannot read Lucide icon ${name}`);
  return new Function(`return ${match[1]}`)();
}

function glyphSvg(nodes, size, color) {
  const shape = nodes.map(([tag, attrs]) => {
    const attributes = Object.entries(attrs).filter(([key]) => key !== 'key')
      .map(([key, value]) => `${key}="${value}"`).join(' ');
    return `<${tag} ${attributes}/>`;
  }).join('');
  const scale = (size * 0.42) / 24;
  const offset = (size - 24 * scale) / 2;
  return `<g transform="translate(${offset} ${offset}) scale(${scale})" fill="none" stroke="${color}"
    stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">${shape}</g>`;
}

function largeSvg(nodes, size) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
    <defs><clipPath id="r"><rect width="${size}" height="${size}" rx="${size * 0.22}" ry="${size * 0.22}"/></clipPath></defs>
    <g clip-path="url(#r)">
      <rect width="${size}" height="${size}" fill="#ffffff"/>
      <ellipse cx="${size * 0.60}" cy="${size * 0.61}" rx="${size * 0.32}" ry="${size * 0.30}" fill="#E91E63" opacity="0.68"/>
      <ellipse cx="${size * 0.41}" cy="${size * 0.39}" rx="${size * 0.31}" ry="${size * 0.29}" fill="#00BCD4" opacity="0.68"/>
      <circle cx="${size * 0.50}" cy="${size * 0.50}" r="${size * 0.25}" fill="#3F51B5" opacity="0.88"/>
      ${glyphSvg(nodes, size, '#ffffff')}
    </g>
  </svg>`;
}

function traySvg(nodes, size) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 ${size} ${size}">
    <rect width="${size}" height="${size}" rx="${size * 0.22}" ry="${size * 0.22}" fill="#3F51B5"/>
    ${glyphSvg(nodes, size, '#ffffff')}
  </svg>`;
}

const nodes = iconNodes('music');
await mkdir(join(root, 'build'), { recursive: true });
const largePng = await sharp(Buffer.from(largeSvg(nodes, 512))).png().toBuffer();
const trayPng = await sharp(Buffer.from(traySvg(nodes, 32))).png().toBuffer();
await writeFile(join(root, 'build', 'icon.png'), largePng);
await writeFile(join(root, 'build', 'tray.png'), trayPng);
await writeFile(join(root, 'src/main/icons.ts'),
  '// Generated by scripts/make-icon-sharp.mjs from a user-provided design; Music glyph from Lucide (ISC). Do not edit by hand.\n'
  + `export const TRAY_ICON_PNG_BASE64 = '${trayPng.toString('base64')}';\n`);
console.log(`icon ok large=${largePng.length} tray=${trayPng.length}`);
